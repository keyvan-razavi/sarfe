export type CatalogMessage = Exclude<keyof typeof messages.fa, "errors">;
export function catalogMessage(locale: Locale, key: CatalogMessage): string {
  return messages[locale][key];
}
export function catalogError(locale: Locale, raw: string): string {
  const m = messages[locale];
  if (/sign-in failed|credentials|authentication|sign in to manage/i.test(raw))
    return m.errorAuth;
  if (/slug|lowercase/i.test(raw)) return m.errors.slug;
  if (/already in use|already exists|P2002/i.test(raw))
    return m.errors.duplicate;
  if (/required/i.test(raw)) return m.errors.required;
  if (/match one|configured options|select/i.test(raw)) return m.errors.select;
  if (/descendant|cycle|parent/i.test(raw)) return m.errors.hierarchy;
  if (/preview/i.test(raw)) return m.previewMutation;
  return m.errors.invalid;
}
